class Companion < Formula
  desc "Generate production-ready Spring Boot REST APIs from natural language"
  homepage "https://github.com/akash/java-companion"
  version "0.1.0"
  license "Apache-2.0"

  # The JAR is published as a GitHub Release asset
  # URL template: https://github.com/akash/java-companion/releases/download/v#{version}/companion.jar
  url "https://github.com/akash/java-companion/releases/download/v#{version}/companion.jar"
  sha256 "REPLACE_WITH_ACTUAL_SHA256_ON_RELEASE"

  depends_on "openjdk@21"

  def install
    libexec.install "companion.jar" => "companion.jar"

    # Create wrapper script
    (bin/"companion").write <<~EOS
      #!/bin/bash
      # Companion CLI - Java Companion Orchestrator
      # Auto-generated by Homebrew formula

      set -euo pipefail

      JAVA_CMD="#{Formula["openjdk@21"].opt_bin}/java"
      JAR_PATH="#{libexec}/companion.jar"

      # Check Java version
      if ! "${JAVA_CMD}" -version 2>&1 | grep -q "version \"2[1-9]"; then
        echo "Error: Java 21+ required. Found:" >&2
        "${JAVA_CMD}" -version 2>&1 | head -1 >&2
        exit 1
      fi

      exec "${JAVA_CMD}" -jar "${JAR_PATH}" "$@"
    EOS
  end

  def caveats
    <<~EOS
      Companion requires Java 21+. Homebrew installs openjdk@21 automatically.

      Quick start:
        companion generate "REST CRUD for Book entity with author, genre, ISBN" --name library

      Run offline (no server needed):
        companion generate "REST API for User management" --name user-service --offline

      Documentation: https://github.com/akash/java-companion#readme
    EOS
  end

  test do
    # Test that the binary runs and shows help
    output = shell_output("#{bin}/companion --help 2>&1")
    assert_match "Generate a new Spring Boot project", output
    assert_match "companion generate", output
  end
end