-- Orchestrator Database Schema
-- Version 1: Initial schema

CREATE TABLE execution_states (
    task_id VARCHAR(64) NOT NULL PRIMARY KEY,
    project_id VARCHAR(128) NOT NULL,
    request VARCHAR(4000) NOT NULL,
    requester VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    plan_json TEXT,
    tool_results_json TEXT,
    error VARCHAR(4000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_execution_project ON execution_states(project_id);
CREATE INDEX idx_execution_status ON execution_states(status);
CREATE INDEX idx_execution_created ON execution_states(created_at);

CREATE TABLE projects (
    id VARCHAR(128) NOT NULL PRIMARY KEY,
    name VARCHAR(256) NOT NULL,
    root_path VARCHAR(1024) NOT NULL,
    memory_path VARCHAR(1024) NOT NULL,
    build_tool VARCHAR(64),
    test_command VARCHAR(256),
    environment_json TEXT,
    registered_at TIMESTAMPTZ NOT NULL,
    last_accessed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_project_name ON projects(name);
CREATE INDEX idx_project_last_accessed ON projects(last_accessed_at);

CREATE TABLE project_memory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(128) NOT NULL,
    type VARCHAR(32) NOT NULL,
    pattern TEXT NOT NULL,
    context TEXT,
    confidence DOUBLE PRECISION,
    usage_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ
);

CREATE INDEX idx_memory_project ON project_memory(project_id);
CREATE INDEX idx_memory_type ON project_memory(type);
CREATE INDEX idx_memory_confidence ON project_memory(confidence DESC);
CREATE INDEX idx_memory_usage ON project_memory(usage_count DESC);

CREATE TABLE repair_sessions (
    repair_id VARCHAR(64) NOT NULL PRIMARY KEY,
    task_id VARCHAR(64) NOT NULL,
    project_id VARCHAR(128) NOT NULL,
    max_attempts INTEGER NOT NULL,
    current_attempt INTEGER DEFAULT 0,
    attempt_timeout_minutes INTEGER NOT NULL,
    total_timeout_minutes INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    error VARCHAR(4000),
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ
);

CREATE INDEX idx_repair_task ON repair_sessions(task_id);
CREATE INDEX idx_repair_project ON repair_sessions(project_id);
CREATE INDEX idx_repair_status ON repair_sessions(status);
CREATE INDEX idx_repair_started ON repair_sessions(started_at);