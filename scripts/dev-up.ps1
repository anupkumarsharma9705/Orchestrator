#!/usr/bin/env pwsh
# One-command local stack: PostgreSQL + orchestrator server with mTLS,
# plus a ready-to-use ~/.companion/config.yaml for the CLI.
#
# Usage:
#   ./scripts/dev-up.ps1
#   ./scripts/dev-up.ps1 -TimeoutSeconds 300
#   ./scripts/dev-up.ps1 -SkipBuild

param(
    [int]$TimeoutSeconds = 240,
    [switch]$SkipBuild
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

$EnvFile = Join-Path $Root ".env"
$CertsDir = Join-Path $Root "certs"
$ConfigDir = Join-Path ([Environment]::GetFolderPath("UserProfile")) ".companion"
$ConfigFile = Join-Path $ConfigDir "config.yaml"
$CliJar = Join-Path $Root "app-cli/target/app-cli-0.0.1-SNAPSHOT-exec.jar"

function New-Secret([int]$ByteCount) {
    $buffer = New-Object byte[] $ByteCount
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return (($buffer | ForEach-Object { $_.ToString("x2") }) -join "")
}

function Get-StringHash([string]$Value) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($Value)
        return ([System.BitConverter]::ToString($sha.ComputeHash($bytes))).Replace("-", "").ToLowerInvariant()
    } finally {
        $sha.Dispose()
    }
}

function Read-DotEnv([string]$Path) {
    $values = @{}
    if (-not (Test-Path $Path)) { return $values }
    foreach ($line in Get-Content -Path $Path) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$') {
            $name = $matches[1]
            $value = $matches[2].Trim()
            if (($value.StartsWith('"') -and $value.EndsWith('"')) -or
                ($value.StartsWith("'") -and $value.EndsWith("'"))) {
                $value = $value.Substring(1, $value.Length - 2)
            }
            $values[$name] = $value
        }
    }
    return $values
}

function Set-DotEnvValue([string]$Path, [string]$Name, [string]$Value) {
    $lines = if (Test-Path $Path) { @(Get-Content -Path $Path) } else { @() }
    $found = $false
    $updated = foreach ($line in $lines) {
        if ($line -match "^\s*$([regex]::Escape($Name))\s*=") {
            $found = $true
            "$Name=$Value"
        } else {
            $line
        }
    }
    if (-not $found) {
        $updated = @($updated) + "$Name=$Value"
    }
    Set-Content -Path $Path -Value $updated -Encoding UTF8
}

function ConvertTo-YamlString([string]$Value) {
    if ($null -eq $Value) { return "''" }
    return "'" + $Value.Replace("'", "''") + "'"
}

function Invoke-Checked([string]$Description, [scriptblock]$Action) {
    & $Action
    if ($LASTEXITCODE -ne 0) {
        throw "$Description failed with exit code $LASTEXITCODE"
    }
}

Write-Host "== Java Companion: local stack ==" -ForegroundColor Cyan

# ----- Prerequisites -------------------------------------------------------
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker is not installed. Install Docker Desktop 27+ and re-run this script."
}
docker info --format '{{.ServerVersion}}' 2>$null | Out-Null
if ($LASTEXITCODE -ne 0) {
    throw "The Docker daemon is not reachable. Start Docker Desktop and re-run this script."
}
docker compose version 2>$null | Out-Null
if ($LASTEXITCODE -ne 0) {
    throw "Docker Compose v2 is required. Update Docker Desktop."
}

$dockerServerVersion = (& docker version --format '{{.Server.Version}}' 2>$null | Out-String).Trim()
$dockerMajor = ($dockerServerVersion -split '\.')[0]
if ([string]::IsNullOrWhiteSpace($dockerServerVersion) -or
    $dockerMajor -notmatch '^\d+$' -or
    [int]$dockerMajor -lt 27) {
    throw "Docker server 27+ is required (found: '$dockerServerVersion'). Upgrade Docker Desktop and re-run."
}

# ----- .env ----------------------------------------------------------------
if (-not (Test-Path $EnvFile)) {
    Write-Host "Creating .env with generated secrets..." -ForegroundColor Yellow
    Set-Content -Path $EnvFile -Encoding UTF8 -Value @(
        "# Generated by scripts/dev-up.ps1. Never commit this file.",
        "ORCHESTRATOR_API_KEY=$(New-Secret 32)",
        "POSTGRES_PASSWORD=$(New-Secret 24)",
        "CERT_PASSWORD=$(New-Secret 24)",
        "NVIDIA_API_KEY=$($env:NVIDIA_API_KEY)",
        "OPENROUTER_API_KEY=$($env:OPENROUTER_API_KEY)",
        "OPENAI_API_KEY=$($env:OPENAI_API_KEY)",
        "KAGGLE_API_KEY=$($env:KAGGLE_API_KEY)",
        "GITHUB_TOKEN=$($env:GITHUB_TOKEN)"
    )
}

$dotenv = Read-DotEnv $EnvFile
$required = @{
    "ORCHESTRATOR_API_KEY" = 32
    "POSTGRES_PASSWORD"    = 16
    "CERT_PASSWORD"        = 6
}
foreach ($name in $required.Keys) {
    $value = $dotenv[$name]
    if ([string]::IsNullOrWhiteSpace($value) -or $value.Length -lt $required[$name]) {
        $value = New-Secret ([Math]::Max(24, $required[$name]))
        Set-DotEnvValue $EnvFile $name $value
        $dotenv[$name] = $value
        Write-Host "Generated $name in .env" -ForegroundColor Yellow
    }
}

# Expose .env values to this process and to docker compose.
foreach ($entry in $dotenv.GetEnumerator()) {
    [Environment]::SetEnvironmentVariable($entry.Key, $entry.Value, "Process")
}

$ServerPort = if ([string]::IsNullOrWhiteSpace($env:ORCHESTRATOR_PORT)) { "8443" } else { $env:ORCHESTRATOR_PORT }

# ----- Certificates --------------------------------------------------------
# The keystores are encrypted with CERT_PASSWORD. If the password changes but
# the old keystores remain, the server cannot open them. Track a hash of the
# password next to the certificates and regenerate when it no longer matches.
$CertMarker = Join-Path $CertsDir ".password-sha256"
$CertPasswordHash = Get-StringHash $dotenv["CERT_PASSWORD"]
$certConfigMatches = (Test-Path (Join-Path $CertsDir "client-keystore.p12")) -and
    (Test-Path $CertMarker) -and
    ((Get-Content -Raw $CertMarker).Trim() -eq $CertPasswordHash)

$CertsRegenerated = $false
if (-not $certConfigMatches) {
    Write-Host "Generating development CA, server and client certificates..." -ForegroundColor Yellow
    & (Join-Path $PSScriptRoot "generate-dev-certs.ps1") -OutputDir $CertsDir
    if ($LASTEXITCODE -ne 0) {
        throw "Certificate generation failed."
    }
    Set-Content -Path $CertMarker -Value $CertPasswordHash -Encoding ascii
    $CertsRegenerated = $true
}

# ----- Stack ---------------------------------------------------------------
Write-Host "Building and starting PostgreSQL + orchestrator-server..." -ForegroundColor Cyan
$composeArgs = @("compose", "up", "-d", "--build")
if ($CertsRegenerated) {
    # The running container still holds the previous keystore in memory.
    $composeArgs += "--force-recreate"
}
Invoke-Checked "docker compose up" { & docker @composeArgs }

Write-Host "Waiting for the server to become healthy (timeout: ${TimeoutSeconds}s)..."
$containerId = (& docker compose ps -q orchestrator-server).Trim()
if ([string]::IsNullOrWhiteSpace($containerId)) {
    throw "Could not find the orchestrator-server container. Run 'docker compose logs' for details."
}

$deadline = (Get-Date).AddSeconds($TimeoutSeconds)
$status = "starting"
$lastPrinted = ""
while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 2
    $status = (& docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' $containerId 2>$null).Trim()
    if ($status -ne $lastPrinted) {
        Write-Host "  status: $status"
        $lastPrinted = $status
    }
    if ($status -eq "healthy" -or $status -eq "running") { break }
    if ($status -eq "unhealthy" -or $status -eq "exited" -or $status -eq "dead") { break }
}

if ($status -ne "healthy" -and $status -ne "running") {
    Write-Host ""
    Write-Host "Server did not become healthy (status: $status)." -ForegroundColor Red
    docker compose logs --tail 120 orchestrator-server
    throw "Startup failed. Inspect the logs above."
}

# ----- CLI configuration ---------------------------------------------------
New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null
if (Test-Path $ConfigFile) {
    $backup = "$ConfigFile.bak." + (Get-Date -Format "yyyyMMddHHmmss")
    Copy-Item $ConfigFile $backup
    Write-Host "Backed up existing CLI config to $backup"
}

$certPathForYaml = $CertsDir.Replace("\", "/")
$yaml = @(
    "# Generated by scripts/dev-up.ps1",
    "serverUrl: 'https://localhost:$ServerPort'",
    "defaultProject: ''",
    "outputFormat: 'table'",
    "timeoutSeconds: 600",
    "apiKey: $(ConvertTo-YamlString $dotenv['ORCHESTRATOR_API_KEY'])",
    "logLevel: 'INFO'",
    "noColor: false",
    "ssl:",
    "  enabled: true",
    "  trustStore: $(ConvertTo-YamlString ($certPathForYaml + '/truststore.p12'))",
    "  trustStorePassword: $(ConvertTo-YamlString $dotenv['CERT_PASSWORD'])",
    "  trustStoreType: 'PKCS12'",
    "  verifyHostname: true",
    "  mtlsEnabled: true",
    "  keyStore: $(ConvertTo-YamlString ($certPathForYaml + '/client-keystore.p12'))",
    "  keyStorePassword: $(ConvertTo-YamlString $dotenv['CERT_PASSWORD'])",
    "  keyStoreType: 'PKCS12'",
    "  keyAlias: 'client'"
)
Set-Content -Path $ConfigFile -Value $yaml -Encoding UTF8

# ----- CLI build -----------------------------------------------------------
if (-not $SkipBuild -and -not (Test-Path $CliJar)) {
    if (Get-Command mvn -ErrorAction SilentlyContinue) {
        Write-Host "Building the CLI..." -ForegroundColor Cyan
        Invoke-Checked "CLI build" { mvn -B -ntp -pl app-cli -am package -DskipTests }
    } else {
        Write-Host "Maven was not found; build the CLI later with: mvn -pl app-cli -am package -DskipTests" -ForegroundColor Yellow
    }
}

Write-Host ""
Write-Host "Stack is up." -ForegroundColor Green
Write-Host "  Server:      https://localhost:$ServerPort (mTLS + API key)"
Write-Host "  CLI config:  $ConfigFile"
if (Test-Path $CliJar) {
    Write-Host ""
    Write-Host "Try (offline generation needs no model provider key):"
    Write-Host "  java -jar `"$CliJar`" doctor"
    Write-Host "  java -jar `"$CliJar`" generate `"REST CRUD for Book`" --name library --offline"
    Write-Host ""
    Write-Host "Server-backed generation requires a provider key (for example NVIDIA_API_KEY)"
    Write-Host "in .env, followed by: docker compose up -d"
} else {
    Write-Host ""
    Write-Host "Build the CLI, then run: java -jar app-cli/target/app-cli-0.0.1-SNAPSHOT-exec.jar doctor"
}
Write-Host ""
Write-Host "Stop the stack with: docker compose down"
