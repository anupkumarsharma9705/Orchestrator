#!/usr/bin/env bash
# One-command local stack: PostgreSQL + orchestrator server with mTLS,
# plus a ready-to-use ~/.companion/config.yaml for the CLI.
#
# Usage:
#   ./scripts/dev-up.sh
#   DEV_UP_TIMEOUT=300 ./scripts/dev-up.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

ENV_FILE="$REPO_ROOT/.env"
CERTS_DIR="$REPO_ROOT/certs"
CONFIG_DIR="$HOME/.companion"
CONFIG_FILE="$CONFIG_DIR/config.yaml"
CLI_JAR="$REPO_ROOT/app-cli/target/app-cli-0.0.1-SNAPSHOT-exec.jar"
TIMEOUT="${DEV_UP_TIMEOUT:-240}"

gen_secret() {
  local bytes="${1:-32}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$bytes"
  else
    head -c "$bytes" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

yaml_quote() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

hash_secret() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf '%s' "$1" | sha256sum | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    printf '%s' "$1" | shasum -a 256 | awk '{print $1}'
  else
    printf '%s' "$1" | openssl dgst -sha256 | awk '{print $NF}'
  fi
}

# Parse KEY=VALUE lines without executing the file as shell code. Values may
# contain spaces or shell metacharacters; surrounding quotes are stripped.
load_env_file() {
  local file="$1" line key value
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    case "$line" in
      ''|'#'*) continue ;;
    esac
    case "$line" in
      *=*) ;;
      *) continue ;;
    esac
    key="${line%%=*}"
    value="${line#*=}"
    case "$key" in
      ''|*[!A-Za-z0-9_]*) continue ;;
      [0-9]*) continue ;;
    esac
    if [ "${#value}" -ge 2 ]; then
      case "$value" in
        \"*\") value="${value:1:${#value}-2}" ;;
        \'*\') value="${value:1:${#value}-2}" ;;
      esac
    fi
    export "$key=$value"
  done < "$file"
}

echo "== Java Companion: local stack =="

# ----- Prerequisites -------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  echo "ERROR: Docker is not installed. Install Docker 27+ and re-run." >&2
  exit 1
fi
if ! docker info >/dev/null 2>&1; then
  echo "ERROR: the Docker daemon is not reachable. Start Docker and re-run." >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "ERROR: Docker Compose v2 is required." >&2
  exit 1
fi

DOCKER_SERVER_VERSION="$(docker version --format '{{.Server.Version}}' 2>/dev/null || true)"
DOCKER_MAJOR="${DOCKER_SERVER_VERSION%%.*}"
case "$DOCKER_MAJOR" in
  ''|*[!0-9]*)
    echo "ERROR: could not determine the Docker server version (found: '${DOCKER_SERVER_VERSION:-unknown}')." >&2
    exit 1
    ;;
esac
if [ "$DOCKER_MAJOR" -lt 27 ]; then
  echo "ERROR: Docker server 27+ is required (found: $DOCKER_SERVER_VERSION). Upgrade Docker and re-run." >&2
  exit 1
fi

# ----- .env ----------------------------------------------------------------
if [ ! -f "$ENV_FILE" ]; then
  echo "Creating .env with generated secrets..."
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/dev-up.sh. Never commit this file.
ORCHESTRATOR_API_KEY=$(gen_secret 32)
POSTGRES_PASSWORD=$(gen_secret 24)
CERT_PASSWORD=$(gen_secret 24)
NVIDIA_API_KEY=${NVIDIA_API_KEY:-}
OPENROUTER_API_KEY=${OPENROUTER_API_KEY:-}
OPENAI_API_KEY=${OPENAI_API_KEY:-}
KAGGLE_API_KEY=${KAGGLE_API_KEY:-}
GITHUB_TOKEN=${GITHUB_TOKEN:-}
EOF
  chmod 600 "$ENV_FILE" 2>/dev/null || true
fi

load_env_file "$ENV_FILE"

append_secret_if_missing() {
  local name="$1" bytes="$2" minimum="$3"
  local current="${!name:-}"
  if [ "${#current}" -lt "$minimum" ]; then
    local value
    value="$(gen_secret "$bytes")"
    printf '\n%s=%s\n' "$name" "$value" >> "$ENV_FILE"
    export "$name=$value"
    echo "Generated $name in .env"
  fi
}

append_secret_if_missing ORCHESTRATOR_API_KEY 32 32
append_secret_if_missing POSTGRES_PASSWORD 24 16
append_secret_if_missing CERT_PASSWORD 24 6

SERVER_PORT="${ORCHESTRATOR_PORT:-8443}"

# ----- Certificates --------------------------------------------------------
# The keystores are encrypted with CERT_PASSWORD. If the password changes but
# the old keystores remain, the server cannot open them. Track a hash of the
# password next to the certificates and regenerate when it no longer matches.
CERT_MARKER="$CERTS_DIR/.password-sha256"
CERT_HASH="$(hash_secret "$CERT_PASSWORD")"
CERTS_REGENERATED=0
if [ ! -f "$CERTS_DIR/client-keystore.p12" ] \
  || [ ! -f "$CERT_MARKER" ] \
  || [ "$(cat "$CERT_MARKER")" != "$CERT_HASH" ]; then
  echo "Generating development CA, server and client certificates..."
  CERT_OUTPUT_DIR="$CERTS_DIR" "$REPO_ROOT/scripts/generate-dev-certs.sh"
  printf '%s\n' "$CERT_HASH" > "$CERT_MARKER"
  CERTS_REGENERATED=1
fi

# The server container and its healthcheck run as uid 1001 and read these
# bind-mounted files. They protect a local development CA only, so make them
# readable; production deployments should use a secret manager instead.
chmod 644 "$CERTS_DIR/server-keystore.p12" "$CERTS_DIR/client-keystore.p12" \
  "$CERTS_DIR/truststore.p12" 2>/dev/null || true

# ----- Stack ---------------------------------------------------------------
echo "Building and starting PostgreSQL + orchestrator-server..."
COMPOSE_ARGS=(up -d --build)
if [ "$CERTS_REGENERATED" = "1" ]; then
  # The running container still holds the previous keystore in memory.
  COMPOSE_ARGS+=(--force-recreate)
fi
docker compose "${COMPOSE_ARGS[@]}"

echo "Waiting for the server to become healthy (timeout: ${TIMEOUT}s)..."
CONTAINER_ID="$(docker compose ps -q orchestrator-server)"
if [ -z "$CONTAINER_ID" ]; then
  echo "ERROR: orchestrator-server container not found." >&2
  docker compose logs --tail 120 orchestrator-server || true
  exit 1
fi

STATUS="starting"
DEADLINE=$(( $(date +%s) + TIMEOUT ))
LAST_PRINTED=""
while [ "$(date +%s)" -lt "$DEADLINE" ]; do
  sleep 2
  STATUS="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$CONTAINER_ID" 2>/dev/null || echo unknown)"
  if [ "$STATUS" != "$LAST_PRINTED" ]; then
    echo "  status: $STATUS"
    LAST_PRINTED="$STATUS"
  fi
  case "$STATUS" in
    healthy|running) break ;;
    unhealthy|exited|dead) break ;;
  esac
done

if [ "$STATUS" != "healthy" ] && [ "$STATUS" != "running" ]; then
  echo
  echo "ERROR: server did not become healthy (status: $STATUS)." >&2
  docker compose logs --tail 120 orchestrator-server || true
  exit 1
fi

# ----- CLI configuration ---------------------------------------------------
mkdir -p "$CONFIG_DIR"
if [ -f "$CONFIG_FILE" ]; then
  BACKUP="$CONFIG_FILE.bak.$(date +%Y%m%d%H%M%S)"
  cp "$CONFIG_FILE" "$BACKUP"
  echo "Backed up existing CLI config to $BACKUP"
fi

cat > "$CONFIG_FILE" <<EOF
# Generated by scripts/dev-up.sh
serverUrl: 'https://localhost:$SERVER_PORT'
defaultProject: ''
outputFormat: 'table'
timeoutSeconds: 600
apiKey: $(yaml_quote "$ORCHESTRATOR_API_KEY")
logLevel: 'INFO'
noColor: false
ssl:
  enabled: true
  trustStore: $(yaml_quote "$CERTS_DIR/truststore.p12")
  trustStorePassword: $(yaml_quote "$CERT_PASSWORD")
  trustStoreType: 'PKCS12'
  verifyHostname: true
  mtlsEnabled: true
  keyStore: $(yaml_quote "$CERTS_DIR/client-keystore.p12")
  keyStorePassword: $(yaml_quote "$CERT_PASSWORD")
  keyStoreType: 'PKCS12'
  keyAlias: 'client'
EOF
chmod 600 "$CONFIG_FILE" 2>/dev/null || true

# ----- CLI build -----------------------------------------------------------
if [ ! -f "$CLI_JAR" ]; then
  if command -v mvn >/dev/null 2>&1; then
    echo "Building the CLI..."
    mvn -B -ntp -pl app-cli -am package -DskipTests
  else
    echo "WARN: Maven not found; build the CLI later with: mvn -pl app-cli -am package -DskipTests"
  fi
fi

echo
echo "Stack is up."
echo "  Server:      https://localhost:$SERVER_PORT (mTLS + API key)"
echo "  CLI config:  $CONFIG_FILE"
if [ -f "$CLI_JAR" ]; then
  echo
  echo "Try (offline generation needs no model provider key):"
  echo "  java -jar \"$CLI_JAR\" doctor"
  echo "  java -jar \"$CLI_JAR\" generate \"REST CRUD for Book\" --name library --offline"
  echo
  echo "Server-backed generation requires a provider key (for example NVIDIA_API_KEY)"
  echo "in .env, followed by: docker compose up -d"
else
  echo
  echo "Build the CLI, then run: java -jar app-cli/target/app-cli-0.0.1-SNAPSHOT-exec.jar doctor"
fi
echo
echo "Stop the stack with: docker compose down"
